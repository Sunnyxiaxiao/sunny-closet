/** 把字面量类型放宽成 string，英文版只要结构相同即可 */
type Widen<T> = T extends string
  ? string
  : T extends (...args: infer A) => infer R
    ? (...args: A) => Widen<R>
    : T extends readonly (infer U)[]
      ? readonly Widen<U>[]
      : T extends object
        ? { [K in keyof T]: Widen<T[K]> }
        : T;

/** 前台文字的结构（不含只有中文的 admin） */
export type Messages = Widen<Omit<typeof messages, "admin">>;
